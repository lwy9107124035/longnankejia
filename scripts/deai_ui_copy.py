def read(p):
    return io.open(os.path.join(ROOT, p), encoding="utf-8").read()


def write(p, s):
    tmp = os.path.join(ROOT, p + ".tmp")
    with io.open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)
    os.replace(tmp, os.path.join(ROOT, p))


def main():
    cache = {}
    bad = 0
    for op, path, old, new in EDITS:
        src = cache.get(path) or read(path)
        cache[path] = src
        n = src.count(old)
        if n == 0 and ((new and new in src) or op == "drop"):
            print("skip %-3s %-14s 已是改后的样子：%s" % (op, path, old[:22]))
            continue
        if n != 1:
            print("MISS %-3s %-14s 命中 %d 次：%s" % (op, path, n, old[:34]))
            bad += 1
            continue
        if op == "rep":
            cache[path] = src.replace(old, new, 1)
            print("ok   rep %-14s %s" % (path, old[:26]))
            continue
        # drop：整行删掉。这一行是答案拼接的一段，上一行结尾的 ' +' 要跟着去掉。
        lines = src.split("\n")
        hit = [i for i, l in enumerate(lines) if old in l]
        if len(hit) != 1:
            print("DROP  %-14s 命中 %d 行：%s" % (path, len(hit), old[:34]))
            bad += 1
            continue
        i = hit[0]
        tail = lines[i].rstrip()
        del lines[i]
        if not tail.endswith("' +"):
            prev = lines[i - 1]
            k = prev.rfind("' +")
            if k != -1 and prev.strip().endswith("' +"):
                lines[i - 1] = prev[:k] + "'"
        cache[path] = "\n".join(lines)
        print("ok   drop %-14s %s" % (path, old[:26]))
    if bad:
        print("\n%d 处锚点没对上，整个改动不落盘" % bad)
        return 1
    for path, src in cache.items():
        write(path, src)
    print("\n%d 处已改" % len(EDITS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
